#define FALLBACK ((const uint8_t[7]){ 0b11111, 0b11111, 0b11111, \
                                       0b11111, 0b11111, 0b11111, 0b11111 })

static const uint8_t *find(char c)
{
    for (size_t i = 0; i < sizeof(font) / sizeof(font[0]); i++) {
        if (font[i].c == c)
            return font[i].b;
    }
    if (c >= 'a' && c <= 'z') {          /* typecase -> uppercase glyphs */
        c = (char)(c - 'a' + 'A');
        for (size_t i = 0; i < sizeof(font) / sizeof(font[0]); i++) {
            if (font[i].c == c)
                return font[i].b;
        }
    }
    return FALLBACK;
}

static const uint8_t space_rows[7] = {0, 0, 0, 0, 0, 0, 0};

void fb_draw_text(int x, int y, const char *s, int scale,
                  uint32_t fg, uint32_t bg)
{
    for (; *s; s++) {
        const uint8_t *g = (*s == ' ' || *s == '\t')
                               ? space_rows
                               : find(*s);
        fb_blit_glyph(x, y, g, scale, fg, bg);
        x += 6 * scale;
    }
}